def validate_recipe_json(recipe_json: dict):
    errors_description = []

    # 1. Root level checks
    expected_keys = {"ingredients", "steps"}
    missing_keys = expected_keys.difference(set(recipe_json.keys()))
    if len(missing_keys) > 0:
        errors_description.append(f"Missing keys in root = {missing_keys}")

    # 2. Ingredient level checks
    if "ingredients" in recipe_json and isinstance(recipe_json["ingredients"], list):
        ing_expected_keys = {"name", "amount", "unit"}
        for i, ing in enumerate(recipe_json["ingredients"]):
            if not isinstance(ing, dict):
                errors_description.append(
                    f"Ingredient at index {i} is not a dictionary."
                )
                continue

            ing_missing_keys = ing_expected_keys.difference(set(ing.keys()))
            if len(ing_missing_keys) > 0:
                errors_description.append(
                    f"Ingredient at index {i} missing keys = {ing_missing_keys}"
                )

    # 3. Step level checks
    if "steps" in recipe_json and isinstance(recipe_json["steps"], list):
        step_expected_keys = {
            "instruction",
            "action",
            "inputs",
            "result_name",
            "metadata",
        }
        for i, step in enumerate(recipe_json["steps"]):
            if not isinstance(step, dict):
                errors_description.append(f"Step at index {i} is not a dictionary.")
                continue

            step_missing_keys = step_expected_keys.difference(set(step.keys()))
            if len(step_missing_keys) > 0:
                errors_description.append(
                    f"Step at index {i} missing keys = {step_missing_keys}"
                )

    return errors_description


def validate_recipe_dag(recipe_json: dict) -> dict:
    """
    Builds a directed graph from the recipe and validates its structural integrity.
    Ensures it is a DAG, ingredients are the only sources, and the final dish is the only sink.
    """
    errors_description = []
    G = nx.DiGraph()

    ingredients = recipe_json.get("ingredients", [])
    steps = recipe_json.get("steps", [])

    if not ingredients or not steps:
        return ["Recipe must contain both ingredients and steps."]

    # 1. Build the Graph
    ingredient_names = set()
    for ing in ingredients:
        if "name" in ing:
            name = ing["name"]
            G.add_node(name, type="ingredient")
            ingredient_names.add(name)

    step_results = []
    for step in steps:
        if "result_name" not in step:
            continue

        result = step["result_name"]
        step_results.append(result)
        G.add_node(result, type="step_result")

        for inp in step.get("inputs", []):
            # If 'inp' doesn't exist, nx implicitly creates it.
            # It will be caught in the source-node check later.
            G.add_edge(inp, result)

    if not step_results:
        return ["No valid steps found to build the graph."]

    final_dish_name = step_results[-1]

    # 2. DAG Validation (Cycle Check)
    if not nx.is_directed_acyclic_graph(G):
        try:
            cycle = nx.find_cycle(G)
            errors_description.append(f"Cycle detected: {cycle}")
        except nx.NetworkXNoCycle:
            errors_description.append("Cycle detected (unknown path).")

        # Return early if it's not a DAG, as source/sink math becomes unreliable
        return errors_description

    # 3. Source Node Validation (In-Degree == 0)
    source_nodes = {node for node, in_degree in G.in_degree() if in_degree == 0}

    # Are there sources that aren't ingredients? (Hallucinated inputs)
    invalid_sources = source_nodes - ingredient_names
    if invalid_sources:
        errors_description.append(
            f"Undefined inputs used as sources: {invalid_sources}"
        )

    # Are there ingredients that aren't sources? (A step overwrote an ingredient)
    overwritten_ingredients = ingredient_names - source_nodes
    if overwritten_ingredients:
        errors_description.append(
            f"Ingredients generated by a step (in-degree > 0): {overwritten_ingredients}"
        )

    # 4. Sink Node Validation (Out-Degree == 0)
    sink_nodes = {node for node, out_degree in G.out_degree() if out_degree == 0}

    if final_dish_name not in sink_nodes:
        errors_description.append(
            f"Final result '{final_dish_name}' is used as an input later, making it not a sink."
        )

    # Are there sinks other than the final dish? (Unused ingredients or dangling step results)
    dangling_nodes = sink_nodes - {final_dish_name}
    if dangling_nodes:
        errors_description.append(
            f"Dangling nodes (unused ingredients or step results): {dangling_nodes}"
        )

    return errors_description


def run_deterministic_eval(recipe_json: dict, model_id: str) -> Evaluation:
    """
    Takes the parsed extraction dictionary, runs JSON and DAG validations on
    RecipeA, RecipeB, and RecipeFusion, and returns a consolidated Evaluation object.
    """

    inf_key: RecipeFusionInferenceKey = RecipeFusionInferenceKey(**recipe_json["key"])

    eval_key = get_deterministic_eval_key(
        inf_key.id, inf_key.cuisine_a, inf_key.cuisine_b, "deterministic"
    )

    # 2. Setup the values payload
    values: Dict[str, Any] = {}
    total_system_errors = 0

    recipe_prefixes = ["RecipeA", "RecipeB", "RecipeFusion"]

    # 3. Iterate through all three recipes
    for prefix in recipe_prefixes:
        parsed_recipe = recipe_json.get(f"{prefix}_parsed")

        # Guard clause in case the JSON failed to parse in the previous step
        if not isinstance(parsed_recipe, dict):
            json_errs = [f"Critical: {prefix}_parsed is missing or not a dictionary."]
            dag_errs = [f"Critical: Cannot build DAG, {prefix}_parsed is invalid."]
        else:
            # Run the validations
            json_errs = validate_recipe_json(parsed_recipe)
            dag_errs = validate_recipe_dag(parsed_recipe)

        # Calculate lengths
        prefix_error_count = len(json_errs) + len(dag_errs)
        total_system_errors += prefix_error_count

        # Store in the values dictionary
        values[f"{prefix}_json_errors"] = json_errs
        values[f"{prefix}_dag_errors"] = dag_errs
        values[f"{prefix}_error_count"] = prefix_error_count

    # Store the aggregate score
    values["total_error_count"] = total_system_errors

    # 4. Return the consolidated object
    return Evaluation(key=eval_key, values=values)


def extract_deterministic_evaluations(filepath: str):
    json_lines = []

    json_lines = load_from_jsonl(filepath, context="Deterministic Evaluations")
    data = [run_deterministic_eval(line) for line in json_lines]

    return data


